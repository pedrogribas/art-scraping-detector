from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd


def plot_top1(summary: pd.DataFrame, output: Path) -> None:
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.bar(summary["method"], summary["top1"] * 100, color=["#2f9e41", "#cd191e", "#2455a4"])
    ax.set_ylabel("Top-1 (%)")
    ax.set_ylim(0, 100)
    ax.set_title("Bloco A: identificação fechada com 500 imagens")
    for index, value in enumerate(summary["top1"] * 100):
        ax.text(index, value + 1, f"{value:.1f}%", ha="center")
    fig.tight_layout()
    fig.savefig(output, dpi=180)
    plt.close(fig)


def plot_category(per_query: pd.DataFrame, output: Path) -> None:
    grouped = per_query.groupby(["category", "method"], dropna=False)["correct"].mean().unstack(fill_value=0) * 100
    ax = grouped.plot(kind="bar", figsize=(10, 5), color=["#2f9e41", "#cd191e", "#2455a4"])
    ax.set_ylabel("Top-1 (%)")
    ax.set_xlabel("Categoria operacional")
    ax.set_title("Bloco A: desempenho por categoria CLIP zero-shot")
    ax.set_ylim(0, 100)
    ax.legend(title="Método")
    plt.tight_layout()
    plt.savefig(output, dpi=180)
    plt.close()


def write_category_table(per_query: pd.DataFrame, output: Path) -> None:
    grouped = (
        per_query.groupby(["category", "method"], dropna=False)["correct"]
        .agg(["count", "mean"])
        .reset_index()
    )
    wide = grouped.pivot(index="category", columns="method", values="mean").fillna(0) * 100
    wide.to_csv(output.with_suffix(".csv"))
    lines = [
        "% Generated by python -m pavd.cli.build_tcc_report",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "\\textbf{Categoria} & \\textbf{N} & \\textbf{SSIM} & \\textbf{SIFT} & \\textbf{CLIP} \\\\",
        "\\midrule",
    ]
    counts = (
        per_query[["query_id", "category"]]
        .drop_duplicates()
        .groupby("category", dropna=False)
        .size()
    )
    for category, row in wide.iterrows():
        lines.append(
            f"{category} & {int(counts[category])} & {row.get('SSIM', 0):.1f}\\% & "
            f"{row.get('SIFT', 0):.1f}\\% & {row.get('CLIP', 0):.1f}\\% \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    output.with_suffix(".tex").write_text("\n".join(lines), encoding="utf-8")


def scale_report(remote_manifest: Path, output: Path) -> dict:
    item_count = 0
    if remote_manifest.is_file():
        item_count = len(pd.read_parquet(remote_manifest, columns=["gallery_id"]))
    target = 100
    official_count = 500
    expanded_count = item_count + official_count
    n = expanded_count
    embedding_bytes = n * 512 * 4
    return {
        "status": "metadata_only",
        "remote_url_only_target": target,
        "current_experiment": "500 local official + 100 URL-only",
        "official_local_rows": official_count,
        "remote_manifest_rows": item_count,
        "combined_catalog_rows": expanded_count,
        "remote_manifest_reaches_target": item_count >= target,
        "visual_metrics_available": False,
        "reason": "metadata/URLs do not contain image bytes or CLIP embeddings",
        "estimated_clip_embedding_gib_float32": embedding_bytes / (1024 ** 3),
        "estimated_flat_index_gib_float32": embedding_bytes / (1024 ** 3),
        "estimated_query_dot_products_for_500_queries": 500 * n * 512,
        "required_for_measured_block_b": [
            "precomputed CLIP embeddings aligned to gallery_id",
            "embedding provenance and model version",
            "FAISS index parameters",
            "same 500 degraded queries",
        ],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Gera tabelas, gráficos e relatório honesto para o TCC")
    parser.add_argument("--input", type=Path, default=Path("results/pavd"))
    parser.add_argument("--categories", type=Path, default=Path("data/gallery/official_categories.parquet"))
    parser.add_argument("--remote-manifest", type=Path, default=Path("data/gallery/remote_manifest.parquet"))
    parser.add_argument("--output", type=Path, default=Path("results/pavd"))
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    summary = pd.read_csv(args.input / "block_a_summary.csv")
    per_query = pd.read_csv(args.input / "block_a_per_query.csv")
    plot_top1(summary, args.output / "block_a_top1.png")
    plot_category(per_query, args.output / "block_a_by_category.png")
    write_category_table(per_query, args.output / "block_a_by_category")
    if args.categories.is_file():
        categories = pd.read_parquet(args.categories)
        categories.groupby("visual_category").size().rename("count").to_csv(args.output / "category_distribution.csv")
        categories["color_mode"].value_counts().rename("count").to_csv(args.output / "color_mode_distribution.csv")
        categories["texture_level"].value_counts().rename("count").to_csv(args.output / "texture_distribution.csv")
    scale = scale_report(args.remote_manifest, args.output)
    (args.output / "block_b_metadata_only.json").write_text(json.dumps(scale, indent=2), encoding="utf-8")
    lines = [
        "% Generated by python -m pavd.cli.build_tcc_report",
        "\\begin{tabular}{lrrr}",
        "\\toprule",
        "\\textbf{Método} & \\textbf{Acertos} & \\textbf{Top-1} & \\textbf{Busca média} \\\\",
        "\\midrule",
    ]
    for row in summary.itertuples(index=False):
        lines.append(f"{row.method} & {row.correct}/{row.query_count} & {row.top1 * 100:.1f}\\% & {row.mean_search_seconds:.4f} s \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    (args.output / "block_a_summary.tex").write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
